"""Governance/fixture tests proving the OQ-035, OQ-036, and OQ-037 decisions
(guidelines.md v0.13, decisions 39-41) before any T10 implementation code
exists.

These tests encode the FROZEN DECISIONS as constants and check them against
the schema and against the real frozen T04/T08 datasets on disk -- they do
not implement, and must not be mistaken for, the T10 semantic validator
itself (which does not exist yet). Per the governance-resolution turn's own
scope, no dataset file is modified or regenerated by these tests.
"""

import json
from pathlib import Path

from jsonschema import Draft202012Validator

ROOT = Path(__file__).resolve().parent.parent
BASE_SCHEMA = json.loads((ROOT / "schemas" / "base_instance.schema.json").read_text(encoding="utf-8"))
EXAMPLE_SCHEMA = json.loads((ROOT / "schemas" / "example.schema.json").read_text(encoding="utf-8"))
BASE_VALIDATOR = Draft202012Validator(BASE_SCHEMA)
EXAMPLE_VALIDATOR = Draft202012Validator(EXAMPLE_SCHEMA)

BASES_PATH = ROOT / "data" / "raw" / "base_instances.jsonl"
RECORDS_PATH = ROOT / "data" / "generated" / "language_realizations.jsonl"


def _load_jsonl(path: Path) -> list:
    records = []
    with path.open(encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                records.append(json.loads(line))
    return records


def _bases() -> list:
    return _load_jsonl(BASES_PATH)


def _records() -> list:
    return _load_jsonl(RECORDS_PATH)


# --- OQ-035 frozen semantic_role mapping (guidelines.md §13.5, decision 39) -

FROZEN_SEMANTIC_ROLE = {
    "PERSON": "PERSON_NAME",
    "ADDRESS": "DELIVERY_ADDRESS",
    "PHONE": "CONTACT_NUMBER",
    "EMAIL": "CONTACT_EMAIL",
    "PAN": "TAX_IDENTIFIER",
    "AADHAAR": "NATIONAL_ID_IDENTIFIER",
    "UPI_ID": "PAYMENT_IDENTIFIER",
    "BANK_ACCOUNT": "PAYMENT_ACCOUNT_IDENTIFIER",
}


def test_frozen_semantic_role_mapping_has_exactly_eight_types():
    assert len(FROZEN_SEMANTIC_ROLE) == 8


def test_frozen_semantic_role_mapping_matches_the_governance_decision():
    assert FROZEN_SEMANTIC_ROLE == {
        "PERSON": "PERSON_NAME",
        "ADDRESS": "DELIVERY_ADDRESS",
        "PHONE": "CONTACT_NUMBER",
        "EMAIL": "CONTACT_EMAIL",
        "PAN": "TAX_IDENTIFIER",
        "AADHAAR": "NATIONAL_ID_IDENTIFIER",
        "UPI_ID": "PAYMENT_IDENTIFIER",
        "BANK_ACCOUNT": "PAYMENT_ACCOUNT_IDENTIFIER",
    }


def test_every_frozen_t04_base_conforms_to_the_semantic_role_mapping():
    bases = _bases()
    assert len(bases) == 100
    for base in bases:
        for pii in base["pii"]:
            expected = FROZEN_SEMANTIC_ROLE[pii["type"]]
            assert pii["semantic_role"] == expected, (
                f"{base['base_id']}: {pii['type']} has semantic_role="
                f"{pii['semantic_role']!r}, expected {expected!r}"
            )


def test_no_unexpected_semantic_role_value_exists_in_the_frozen_dataset():
    observed = {}
    for base in _bases():
        for pii in base["pii"]:
            observed.setdefault(pii["type"], set()).add(pii["semantic_role"])
    assert observed == {t: {r} for t, r in FROZEN_SEMANTIC_ROLE.items()}


def test_no_unexpected_pii_type_exists_in_the_frozen_dataset():
    observed_types = {pii["type"] for base in _bases() for pii in base["pii"]}
    assert observed_types == set(FROZEN_SEMANTIC_ROLE)


def test_semantic_role_remains_unconstrained_free_text_on_the_schema():
    """The type-fixed mapping is cross-field logic (base.type constrains what
    semantic_role should be), enforced by a validator, not the schema -- the
    schema itself must stay structure-only, consistent with the T02 scope
    rule. This governance decision does not add an enum."""
    pii_item = BASE_SCHEMA["properties"]["pii"]["items"]
    assert pii_item["properties"]["semantic_role"] == {
        "type": "string",
        "minLength": 1,
    }
    assert "enum" not in pii_item["properties"]["semantic_role"]


def test_a_base_instance_using_the_frozen_mapping_is_schema_valid():
    for pii_type, role in FROZEN_SEMANTIC_ROLE.items():
        base = {
            "base_id": f"{pii_type}_999",
            "base_kind": "POSITIVE",
            "pii": [{"type": pii_type, "base_pii_value": "X", "semantic_role": role}],
            "person_context": None,
            "scenario": {"domain": "general_conversation", "purpose": "test"},
            "address_structure": None,
            "canonical_text": f"Test sentence with {pii_type} value X.",
            "synthetic": True,
            "generator_version": "0.1.0",
        }
        BASE_VALIDATOR.validate(base)


def test_a_base_instance_with_a_wrong_semantic_role_is_still_schema_valid_but_violates_the_mapping():
    """Schema validity and mapping conformance are deliberately separate --
    the schema stays permissive; the governance table is what a future T10
    checks the value against."""
    base = {
        "base_id": "PAN_999",
        "base_kind": "POSITIVE",
        "pii": [{"type": "PAN", "base_pii_value": "X", "semantic_role": "NOT_A_REAL_ROLE"}],
        "person_context": None,
        "scenario": {"domain": "general_conversation", "purpose": "test"},
        "address_structure": None,
        "canonical_text": "Test sentence with PAN value X.",
        "synthetic": True,
        "generator_version": "0.1.0",
    }
    BASE_VALIDATOR.validate(base)  # schema allows it
    assert base["pii"][0]["semantic_role"] != FROZEN_SEMANTIC_ROLE["PAN"]  # mapping rejects it


# --- OQ-036 frozen EN canonical-text equality contract (guidelines.md §13.6,
#     decision 40) ------------------------------------------------------------


def test_canonical_text_field_exists_on_the_base_instance_schema():
    """Schema-compatibility check: the OQ-036 contract's oracle field must
    already exist and be required -- it is not a new field this decision
    introduces."""
    assert "canonical_text" in BASE_SCHEMA["required"]
    assert BASE_SCHEMA["properties"]["canonical_text"]["type"] == "string"


def test_text_and_language_fields_exist_on_the_example_schema():
    assert "text" in EXAMPLE_SCHEMA["required"]
    assert "language" in EXAMPLE_SCHEMA["required"]
    assert "EN" in EXAMPLE_SCHEMA["$defs"]["language"]["enum"]


def test_every_frozen_en_record_equals_its_base_canonical_text_exactly():
    """The empirical fact the OQ-036 contract formalizes: EN's derived text
    was already, by construction, byte-identical to the source base's
    canonical_text for every one of the 624 frozen records. Proves the
    contract is not a new invented requirement but an existing invariant."""
    bases_by_id = {b["base_id"]: b for b in _bases()}
    en_records = [r for r in _records() if r["language"] == "EN"]
    assert len(en_records) == 100
    for record in en_records:
        base = bases_by_id[record["base_id"]]
        assert record["text"] == base["canonical_text"], record["variant_id"]


def test_en_canonical_text_equality_contract_is_schema_compatible():
    """The contract as stated (record.text == base.canonical_text) only
    references fields both schemas already require -- introduces no new
    field and no schema change."""
    assert "canonical_text" in BASE_SCHEMA["properties"]
    assert "text" in EXAMPLE_SCHEMA["properties"]


def semantic_use_contract_passes(record: dict, base: dict) -> bool:
    """The frozen OQ-036 rule, reproduced exactly as a governance-decision
    test helper (guidelines.md §13.6) -- not the T10 implementation, which
    does not exist yet. Applies only to unperturbed EXPLICIT EN records; any
    other record is out of this contract's scope and this helper does not
    judge it."""
    if not (
        record["language"] == "EN"
        and record["context"] == "EXPLICIT"
        and record["perturbation"]["family"] == "NONE"
    ):
        raise ValueError("OQ-036's contract only covers unperturbed EN/EXPLICIT records")
    return record["text"] == base["canonical_text"]


def test_contract_helper_passes_on_every_frozen_en_record():
    bases_by_id = {b["base_id"]: b for b in _bases()}
    for record in _records():
        if record["language"] != "EN":
            continue
        base = bases_by_id[record["base_id"]]
        assert semantic_use_contract_passes(record, base)


def test_contract_helper_fails_on_a_mutated_en_sentence():
    base = {"base_id": "PAN_001", "canonical_text": "My PAN number is ABCDE1234F."}
    mutated_record = {
        "language": "EN",
        "context": "EXPLICIT",
        "perturbation": {"family": "NONE"},
        "text": "My reference number is ABCDE1234F.",  # role swapped in the sentence
    }
    assert semantic_use_contract_passes(mutated_record, base) is False


def test_contract_helper_declines_to_judge_non_en_conditions():
    base = {"base_id": "PAN_001", "canonical_text": "My PAN number is ABCDE1234F."}
    non_en_record = {
        "language": "HINGLISH",
        "context": "EXPLICIT",
        "perturbation": {"family": "NONE"},
        "text": "bhai mera PAN ABCDE1234F hai",
    }
    try:
        semantic_use_contract_passes(non_en_record, base)
        assert False, "expected ValueError for a condition outside the OQ-036 contract"
    except ValueError:
        pass


def test_contract_helper_declines_to_judge_perturbed_en_records():
    base = {"base_id": "PAN_001", "canonical_text": "My PAN number is ABCDE1234F."}
    perturbed_record = {
        "language": "EN",
        "context": "EXPLICIT",
        "perturbation": {"family": "A1"},
        "text": "My PAN number is ABCDE1234F.",
    }
    try:
        semantic_use_contract_passes(perturbed_record, base)
        assert False, "expected ValueError for a perturbed record"
    except ValueError:
        pass


