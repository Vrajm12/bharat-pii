# --- OQ-037 frozen IN_EN / five-condition label contract (guidelines.md
#     §13.7, decision 41) -----------------------------------------------------

LABEL_LATIN = {
    "PERSON": "naam",
    "ADDRESS": "address",
    "PHONE": "mobile",
    "EMAIL": "email",
    "PAN": "PAN",
    "AADHAAR": "Aadhaar",
    "UPI_ID": "UPI",
    "BANK_ACCOUNT": "account",
}

LABEL_DEVANAGARI = {
    "PERSON": "नाम",
    "ADDRESS": "एड्रेस",
    "PHONE": "मोबाइल",
    "EMAIL": "ईमेल",
    "PAN": "PAN",
    "AADHAAR": "आधार",
    "UPI_ID": "UPI",
    "BANK_ACCOUNT": "अकाउंट",
}

LATIN_LABEL_CONDITIONS = ("ROM_HI", "HINGLISH", "INFORMAL_HINGLISH")
DEVANAGARI_LABEL_CONDITIONS = ("HI_LATIN_PII", "HI_DEVA_PII")


def test_label_tables_have_exactly_eight_types_each():
    assert len(LABEL_LATIN) == 8
    assert len(LABEL_DEVANAGARI) == 8
    assert set(LABEL_LATIN) == set(FROZEN_SEMANTIC_ROLE)
    assert set(LABEL_DEVANAGARI) == set(FROZEN_SEMANTIC_ROLE)


def test_pan_and_upi_id_labels_stay_latin_even_in_the_devanagari_carrier():
    """The one deliberate exception in the table (guidelines.md §4.13's own
    note): PAN and UPI stay Latin acronyms even inside Devanagari carrier
    text."""
    assert LABEL_DEVANAGARI["PAN"] == "PAN"
    assert LABEL_DEVANAGARI["UPI_ID"] == "UPI"


def test_aadhaar_label_is_the_same_word_in_both_registers():
    """Aadhaar is Hindi-origin vocabulary, not an English loanword (§4.13) --
    it is not translated, only re-scripted."""
    assert LABEL_LATIN["AADHAAR"] == "Aadhaar"
    assert LABEL_DEVANAGARI["AADHAAR"] == "आधार"


def semantic_use_contract_v2(record: dict, base: dict) -> bool:
    """The complete OQ-036 + OQ-037 contract, reproduced as a governance-
    decision test helper covering all seven language conditions -- not the
    T10 implementation, which does not exist yet."""
    language = record["language"]
    pii_type = base["pii"][0]["type"]
    if language == "EN":
        return record["text"] == base["canonical_text"]
    if language == "IN_EN":
        return base["canonical_text"] in record["text"]
    if language in LATIN_LABEL_CONDITIONS:
        return LABEL_LATIN[pii_type].lower() in record["text"].lower()
    if language in DEVANAGARI_LABEL_CONDITIONS:
        return LABEL_DEVANAGARI[pii_type] in record["text"]
    raise ValueError(f"unrecognized language condition: {language!r}")


def test_complete_contract_passes_on_every_one_of_the_624_frozen_records():
    bases_by_id = {b["base_id"]: b for b in _bases()}
    records = _records()
    assert len(records) == 624
    failures = []
    for record in records:
        base = bases_by_id[record["base_id"]]
        if not semantic_use_contract_v2(record, base):
            failures.append(record["variant_id"])
    assert failures == []


def test_complete_contract_covers_every_record_with_no_unrecognized_language():
    bases_by_id = {b["base_id"]: b for b in _bases()}
    for record in _records():
        base = bases_by_id[record["base_id"]]
        semantic_use_contract_v2(record, base)  # raises ValueError if uncovered


def test_in_en_contract_fails_when_canonical_text_is_absent():
    base = {"pii": [{"type": "PAN"}], "canonical_text": "My PAN number is ABCDE1234F."}
    record = {"language": "IN_EN", "text": "Kindly note: my reference is ABCDE1234F."}
    assert semantic_use_contract_v2(record, base) is False


def test_in_en_contract_passes_with_a_wrapping_marker():
    base = {"pii": [{"type": "PAN"}], "canonical_text": "My PAN number is ABCDE1234F."}
    record = {"language": "IN_EN", "text": "Kindly note: My PAN number is ABCDE1234F."}
    assert semantic_use_contract_v2(record, base) is True


def test_romanized_label_contract_rejects_wrong_role_label():
    """A hand-mutated record whose text carries a different type's label
    instead of its own declared type's -- must be rejected, not silently
    accepted because the PII value itself is present."""
    base = {"pii": [{"type": "AADHAAR"}], "canonical_text": "My Aadhaar number is 123456789012."}
    wrong_role_record = {"language": "HINGLISH", "text": "mera account number 123456789012 hai"}
    assert semantic_use_contract_v2(wrong_role_record, base) is False


def test_romanized_label_contract_rejects_role_never_asserted():
    base = {"pii": [{"type": "PHONE"}], "canonical_text": "My phone number is 9876543210."}
    bare_value_record = {"language": "ROM_HI", "text": "9876543210 hai"}
    assert semantic_use_contract_v2(bare_value_record, base) is False


def test_romanized_label_contract_is_case_insensitive():
    """Justified by guidelines.md §4.14's own frozen INFORMAL_HINGLISH
    all-lowercase feature -- casing cannot be part of this check."""
    base = {"pii": [{"type": "EMAIL"}], "canonical_text": "Email me at x@mail.test."}
    lowercase_record = {"language": "INFORMAL_HINGLISH", "text": "email pe msg kr x@mail.test"}
    assert semantic_use_contract_v2(lowercase_record, base) is True


def test_devanagari_label_contract_passes_on_the_matched_hi_pair():
    """HI_LATIN_PII and HI_DEVA_PII share byte-identical carrier text
    (§4.11) -- the label check must agree for both members of the pair."""
    base = {"pii": [{"type": "PERSON"}], "canonical_text": "My name is Rahul Sharma."}
    latin_pii_record = {"language": "HI_LATIN_PII", "text": "मेरा नाम Rahul Sharma है।"}
    deva_pii_record = {"language": "HI_DEVA_PII", "text": "मेरा नाम राहुल शर्मा है।"}
    assert semantic_use_contract_v2(latin_pii_record, base) is True
    assert semantic_use_contract_v2(deva_pii_record, base) is True


def test_devanagari_label_contract_applies_uniformly_to_collapsed_records():
    """Non-transliterable types collapse to a single HI_LATIN_PII record
    (§8.1) whose carrier is still Devanagari -- no special-casing needed."""
    base = {"pii": [{"type": "BANK_ACCOUNT"}], "canonical_text": "My bank account number is 123456789012."}
    collapsed_record = {
        "language": "HI_LATIN_PII",
        "hi_variant_collapsed": True,
        "text": "मेरा बैंक अकाउंट नंबर 123456789012 है।",
    }
    assert semantic_use_contract_v2(collapsed_record, base) is True


